/**
 * Windows service rendering — a per-user Task Scheduler task + a supervisor.
 *
 * Windows has no systemd, and a real Windows Service needs a wrapper binary
 * (the exe must speak the service-control protocol) plus admin rights. A
 * scheduled task needs neither, so it is the Windows counterpart of
 * `systemd --user`: starts at logon, runs as the user, no root.
 *
 * Two artifacts, both rendered here so nothing is hand-maintained:
 *   - the task XML, registered with `schtasks /Create /XML`;
 *   - `grounded-service.mjs`, the action the task runs. It sets the env the
 *     api reads, spawns grounded-api, appends its output to a log file,
 *     restarts it on exit, and records pids for `grounded stop`.
 *
 * Measured on Windows 11 (2026-10-15):
 *   - S4U logon runs in session 0: no console window, starts without a
 *     desktop session, and `schtasks /End` kills the whole process tree.
 *     Registering it worked from a non-elevated token.
 *   - InteractiveToken (the fallback) runs on the user's desktop, so the action
 *     is wrapped in `conhost.exe --headless` to keep a console from opening.
 *     `/End` then kills only conhost and orphans node — so stop also kills the
 *     pids the supervisor records, and the supervisor exits when its parent dies.
 *   - Under S4U the parent is the scheduler's SYSTEM svchost: probing it with
 *     `process.kill(pid, 0)` throws EPERM. Only ESRCH means the parent is gone.
 *   - %USERDOMAIN% can read `WORKGROUP` over SSH; the principal is the SID.
 */
import { join } from "node:path";
import { DEFAULT_PORT } from "./detect.js";

/** Task name in the root Task Scheduler folder. */
export const WINDOWS_TASK = "Grounded";

/** S4U = background, session 0, no window. InteractiveToken = only while logged on. */
export type WindowsLogonType = "S4U" | "InteractiveToken";

export interface WindowsServicePaths {
  dir: string;
  launcher: string;
  xml: string;
  log: string;
  pid: string;
}

/** Where the Windows backend keeps its artifacts, all inside the cabinet root. */
export function windowsServicePaths(home: string): WindowsServicePaths {
  const dir = join(home, "service");
  return {
    dir,
    launcher: join(dir, "grounded-service.mjs"),
    xml: join(dir, "grounded-task.xml"),
    log: join(home, "logs", "grounded.log"),
    pid: join(home, "service", "grounded.pid"),
  };
}

export interface LauncherOptions {
  home: string;
  /** absolute path to the grounded-api entry point (`api.mjs` / `bin.js`). */
  apiBin: string;
  port?: number;
  host?: string;
  token?: string;
}

/**
 * Render the supervisor the task runs. Values are embedded with JSON.stringify,
 * so Windows paths and tokens need no escaping of their own.
 */
export function renderServiceLauncher(o: LauncherOptions): string {
  const p = windowsServicePaths(o.home);
  const env: Record<string, string> = {
    GROUNDED_HOME: o.home,
    GROUNDED_API_HOST: o.host ?? "127.0.0.1",
    GROUNDED_API_PORT: String(o.port ?? DEFAULT_PORT),
    GROUNDED_API_UI: "1",
  };
  if (o.token) env.GROUNDED_API_TOKEN = o.token;
  const s = JSON.stringify;
  return `// Generated by \`grounded install --method windows-task\`. Re-run install to change it.
import { spawn } from "node:child_process";
import { openSync, closeSync, statSync, renameSync, writeFileSync, rmSync } from "node:fs";

const API = ${s(o.apiBin)};
const LOG = ${s(p.log)};
const PID = ${s(p.pid)};
const ENV = { ...process.env, ...${s(env)} };
const LOG_MAX = 10 * 1024 * 1024;

function rotate() {
  try {
    if (statSync(LOG).size > LOG_MAX) renameSync(LOG, LOG + ".1");
  } catch {}
}
function note(msg) {
  const fd = openSync(LOG, "a");
  writeFileSync(fd, new Date().toISOString() + " [service] " + msg + "\\n");
  closeSync(fd);
}

let child = null;
let stopping = false;
let backoff = 1000;

function start() {
  rotate();
  const fd = openSync(LOG, "a");
  const startedAt = Date.now();
  child = spawn(process.execPath, [API], { env: ENV, stdio: ["ignore", fd, fd], windowsHide: true });
  closeSync(fd);
  writeFileSync(PID, JSON.stringify({ supervisor: process.pid, api: child.pid }) + "\\n");
  child.on("exit", (code, signal) => {
    if (stopping) return;
    if (Date.now() - startedAt > 60000) backoff = 1000;
    note("grounded-api exited (" + (signal ?? code) + "), restarting in " + backoff + " ms");
    setTimeout(start, backoff);
    backoff = Math.min(backoff * 2, 30000);
  });
}

function stop(why) {
  if (stopping) return;
  stopping = true;
  note("supervisor stopping: " + why);
  try { child?.kill(); } catch {}
  try { rmSync(PID, { force: true }); } catch {}
  process.exit(0);
}
process.on("SIGINT", () => stop("SIGINT"));
process.on("SIGTERM", () => stop("SIGTERM"));

// Under the InteractiveToken fallback, \`schtasks /End\` kills only the conhost
// parent. Exit with it so the api is never orphaned. Only ESRCH means gone:
// under S4U the parent is the scheduler's SYSTEM svchost, which answers EPERM.
const parent = process.ppid;
setInterval(() => {
  try { process.kill(parent, 0); } catch (e) { if (e.code === "ESRCH") stop("parent " + parent + " exited"); }
}, 5000).unref();

note("supervisor " + process.pid + " starting " + API);
start();
`;
}

export interface TaskXmlOptions {
  /** the user's SID — the principal and the logon trigger's user. */
  sid: string;
  logonType: WindowsLogonType;
  /** absolute node.exe. */
  nodePath: string;
  /** absolute grounded-service.mjs. */
  launcherPath: string;
  /** working directory for the action; the cabinet root. */
  workDir: string;
}

function xmlEscape(v: string): string {
  return v
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/**
 * Render the Task Scheduler XML. Write it as UTF-16LE with a BOM — the
 * encoding the declaration names, and the one schtasks reads reliably.
 *
 * Settings that matter on a laptop: a default task refuses to start on
 * battery and is killed when power is unplugged, and stops after 72 h.
 */
export function renderTaskXml(o: TaskXmlOptions): string {
  const node = `"${o.nodePath}"`;
  const launcher = `"${o.launcherPath}"`;
  // S4U runs in session 0 and never shows a window. A logon-session task would
  // open a console for node.exe, so it runs node through a headless conhost.
  const [command, args] =
    o.logonType === "S4U"
      ? [o.nodePath, launcher]
      : ["C:\\Windows\\System32\\conhost.exe", `--headless ${node} ${launcher}`];
  return [
    `<?xml version="1.0" encoding="UTF-16"?>`,
    `<Task version="1.4" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">`,
    `  <RegistrationInfo>`,
    `    <Description>Grounded — self-hosted continuity API + console</Description>`,
    `  </RegistrationInfo>`,
    `  <Triggers>`,
    `    <LogonTrigger>`,
    `      <Enabled>true</Enabled>`,
    `      <UserId>${xmlEscape(o.sid)}</UserId>`,
    `    </LogonTrigger>`,
    `  </Triggers>`,
    `  <Principals>`,
    `    <Principal id="Author">`,
    `      <UserId>${xmlEscape(o.sid)}</UserId>`,
    `      <LogonType>${o.logonType}</LogonType>`,
    `      <RunLevel>LeastPrivilege</RunLevel>`,
    `    </Principal>`,
    `  </Principals>`,
    `  <Settings>`,
    `    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>`,
    `    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>`,
    `    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>`,
    `    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>`,
    `    <StartWhenAvailable>true</StartWhenAvailable>`,
    `    <RestartOnFailure>`,
    `      <Interval>PT1M</Interval>`,
    `      <Count>3</Count>`,
    `    </RestartOnFailure>`,
    `  </Settings>`,
    `  <Actions Context="Author">`,
    `    <Exec>`,
    `      <Command>${xmlEscape(command)}</Command>`,
    `      <Arguments>${xmlEscape(args)}</Arguments>`,
    `      <WorkingDirectory>${xmlEscape(o.workDir)}</WorkingDirectory>`,
    `    </Exec>`,
    `  </Actions>`,
    `</Task>`,
    ``,
  ].join("\r\n");
}


// ---- the cabinet folder's icon ----------------------------------------------

/** desktop.ini for the cabinet root: Explorer shows the Grounded mark instead of
 *  a plain folder, the way it decorates Documents and Downloads. */
export function renderDesktopIni(): string {
  return [
    "[.ShellClassInfo]",
    "IconResource=grounded.ico,0",
    "InfoTip=Grounded: your agents' memory. Facts, sessions and docs live here.",
    "",
  ].join("\r\n");
}

/**
 * Give the Windows cabinet folder the Grounded icon. Best-effort and silent:
 * a folder without an icon is cosmetic, never a reason to fail an install.
 *
 * Explorer reads desktop.ini only when the FOLDER carries the read-only (or
 * system) attribute. On a folder, read-only does not make its contents
 * read-only. The icon and desktop.ini are hidden + system so the folder shows
 * only the user's cabinet.
 */
export async function decorateWindowsFolder(home: string): Promise<boolean> {
  if (process.platform !== "win32") return false;
  try {
    const { writeFileSync, existsSync, readFileSync } = await import("node:fs");
    const { execFile } = await import("node:child_process");
    const { GROUNDED_ICO_BASE64 } = await import("./windows-icon.js");
    const ico = Buffer.from(GROUNDED_ICO_BASE64, "base64");
    const icoPath = join(home, "grounded.ico");
    const iniPath = join(home, "desktop.ini");
    const attrib = (args: string[]) =>
      new Promise<void>((res) => execFile("attrib", args, { timeout: 5000 }, () => res()));

    // attrib +h +s files are not writable in place; clear first, rewrite, re-set.
    const ini = renderDesktopIni();
    const icoCurrent = existsSync(icoPath) && readFileSync(icoPath).equals(ico);
    const iniCurrent = existsSync(iniPath) && readFileSync(iniPath, "utf8") === ini;
    if (!icoCurrent || !iniCurrent) {
      await attrib(["-h", "-s", "-r", icoPath]);
      await attrib(["-h", "-s", "-r", iniPath]);
      if (!icoCurrent) writeFileSync(icoPath, ico);
      if (!iniCurrent) writeFileSync(iniPath, ini, "utf8");
    }
    await attrib(["+h", "+s", icoPath]);
    await attrib(["+h", "+s", iniPath]);
    await attrib(["+r", home]);
    return true;
  } catch {
    return false;
  }
}
